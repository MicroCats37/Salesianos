"""
Integration tests — partial brackets of 3, 5, 6, 7 and 8 teams (Phase 1).

The bracket is NEVER generated by the system: the administrator creates the
rounds, places the teams and decides manually which team gets the bye. These
tests build the bracket exactly as an administrator would and then prove
that:

- no participant is invented (the slots of the later rounds stay empty),
- the byes are exactly the ones the administrator marked,
- a bye has one single participant, no schedule, no score and the
  participant is its winner,
- the bracket stays readable and editable while it is partial.
"""
import pytest
from asgiref.sync import async_to_sync

from modules.competencias.domain.models import CompetenciaEquipo, Encuentro, Ronda
from modules.competencias.domain.schemas.competencias_schemas import (
    EncuentroCreateData,
    RondaCreateData,
)
from modules.competencias.tests.factories import make_bracket_parcial_payload

EQUIPOS = (3, 5, 6, 7, 8)


def _construir_bracket(
    orquestador_rondas,
    orquestador_encuentros,
    orquestador_competencia_equipos,
    competencia,
    equipos,
    actor,
):
    """Build the manual bracket of the competition with the given teams."""
    entradas = []
    for indice, equipo in enumerate(equipos):
        entradas.append(
            async_to_sync(orquestador_competencia_equipos.incorporar_equipo_proceso)(
                str(competencia.id),
                str(equipo.id),
                indice + 1,
                actor,
            )
        )

    plan = make_bracket_parcial_payload(len(equipos))
    for ronda_plan in plan["rondas"]:
        ronda = async_to_sync(orquestador_rondas.crear_ronda_proceso)(
            str(competencia.id),
            RondaCreateData(
                etiqueta=ronda_plan["etiqueta"],
                orden=ronda_plan["orden"],
            ),
            actor,
        )
        for encuentro_plan in ronda_plan["encuentros"]:
            participante_1 = (
                str(entradas[encuentro_plan["participante_1"]].id)
                if encuentro_plan["participante_1"] is not None
                else None
            )
            participante_2 = (
                str(entradas[encuentro_plan["participante_2"]].id)
                if encuentro_plan["participante_2"] is not None
                else None
            )
            encuentro = async_to_sync(
                orquestador_encuentros.crear_encuentro_proceso
            )(
                str(ronda.id),
                EncuentroCreateData(
                    orden=encuentro_plan["orden"],
                    participante_1_id=participante_1,
                    participante_2_id=participante_2,
                ),
                actor,
            )
            if encuentro_plan["es_bye"]:
                async_to_sync(orquestador_encuentros.configurar_bye_proceso)(
                    str(encuentro.id),
                    actor,
                    "Pase manual asignado por el administrador",
                )
    return plan


@pytest.mark.parametrize("num_equipos", EQUIPOS)
@pytest.mark.django_db
def test_el_sistema_no_inventa_participantes_ni_byes(
    orquestador_rondas,
    orquestador_encuentros,
    orquestador_competencia_equipos,
    usuario_admin_competencias,
    competencia,
    crear_equipos_competencia,
    num_equipos,
):
    """GIVEN: a partial bracket WHEN: it is built THEN: nothing is invented."""
    equipos = crear_equipos_competencia(num_equipos)
    plan = _construir_bracket(
        orquestador_rondas,
        orquestador_encuentros,
        orquestador_competencia_equipos,
        competencia,
        equipos,
        usuario_admin_competencias,
    )

    encuentros = Encuentro.objects.filter(ronda__competencia=competencia).order_by(
        "ronda__orden",
        "orden",
    )

    # The rounds of the plan exist with their manual label and order.
    assert [
        ronda.etiqueta
        for ronda in Ronda.objects.filter(competencia=competencia).order_by("orden")
    ] == [ronda["etiqueta"] for ronda in plan["rondas"]]

    # Every encounter of the plan exists, with the slots the administrator
    # typed and nothing else.
    assert encuentros.count() == sum(
        len(ronda["encuentros"]) for ronda in plan["rondas"]
    )

    # Only the first round was filled by the administrator.
    for ronda in Ronda.objects.filter(competencia=competencia).order_by("orden"):
        for encuentro in Encuentro.objects.filter(ronda=ronda).order_by("orden"):
            if ronda.orden == 1:
                continue
            assert encuentro.participante_1_id is None
            assert encuentro.participante_2_id is None
            assert encuentro.estado == "BORRADOR"
            assert encuentro.es_bye is False

    # Every team of the list is in the bracket exactly once.
    assert CompetenciaEquipo.objects.filter(competencia=competencia).count() == num_equipos


@pytest.mark.parametrize("num_equipos", EQUIPOS)
@pytest.mark.django_db
def test_los_byes_son_los_manuales_y_no_los_automaticos(
    orquestador_rondas,
    orquestador_encuentros,
    orquestador_competencia_equipos,
    usuario_admin_competencias,
    competencia,
    crear_equipos_competencia,
    num_equipos,
):
    """GIVEN: an odd bracket WHEN: the byes are set THEN: only the manual ones."""
    equipos = crear_equipos_competencia(num_equipos)
    plan = _construir_bracket(
        orquestador_rondas,
        orquestador_encuentros,
        orquestador_competencia_equipos,
        competencia,
        equipos,
        usuario_admin_competencias,
    )

    byes_plan = [
        encuentro
        for ronda in plan["rondas"]
        for encuentro in ronda["encuentros"]
        if encuentro["es_bye"]
    ]
    byes_realizados = list(
        Encuentro.objects.filter(ronda__competencia=competencia, es_bye=True)
    )

    # The system NEVER chooses a bye: only the planned ones exist.
    assert len(byes_realizados) == len(byes_plan)
    assert len(byes_realizados) == (1 if num_equipos % 2 else 0)

    for bye in byes_realizados:
        # Exactly one participant, no schedule, no score and the participant
        # is the winner.
        participantes = [
            participante
            for participante in (bye.participante_1_id, bye.participante_2_id)
            if participante is not None
        ]
        assert len(participantes) == 1
        assert bye.inicio_programado is None
        assert bye.fin_programado is None
        assert bye.puntaje_1 is None
        assert bye.puntaje_2 is None
        assert bye.marcador_detalle == ""
        assert bye.estado == "FINALIZADO"
        assert bye.ganador_id == participantes[0]
        assert bye.finalizado_en is not None


@pytest.mark.parametrize("num_equipos", EQUIPOS)
@pytest.mark.django_db
def test_el_cuadro_parcial_permanece_editable(
    orquestador_rondas,
    orquestador_encuentros,
    orquestador_competencia_equipos,
    usuario_admin_competencias,
    competencia,
    crear_equipos_competencia,
    num_equipos,
):
    """GIVEN: a partial bracket WHEN: it is read and edited THEN: it stays usable."""
    equipos = crear_equipos_competencia(num_equipos)
    _construir_bracket(
        orquestador_rondas,
        orquestador_encuentros,
        orquestador_competencia_equipos,
        competencia,
        equipos,
        usuario_admin_competencias,
    )

    # The later rounds are still BORRADOR and can receive a participant.
    vacio = Encuentro.objects.filter(
        ronda__competencia=competencia,
        estado="BORRADOR",
        participante_1__isnull=True,
    ).first()
    assert vacio is not None

    entrada = CompetenciaEquipo.objects.filter(competencia=competencia).first()
    actualizado = async_to_sync(orquestador_encuentros.asignar_participantes_proceso)(
        str(vacio.id),
        str(entrada.id),
        None,
        usuario_admin_competencias,
        "Ingreso manual del equipo en el cuadro parcial",
    )

    assert actualizado.participante_1_id == str(entrada.id)
    assert actualizado.estado == "BORRADOR"
